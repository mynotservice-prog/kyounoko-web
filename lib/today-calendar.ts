/** 日付（Dateオブジェクト）から「今日は何の日 / 季節メッセージ」を返す。 */
export function getWhatDay(d: Date): string {
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return WHAT_DAY[`${mm}-${dd}`] ?? SEASON_MESSAGE[d.getMonth() + 1] ?? '';
}

/** 年内通算日（1-366）。date-seeded 選択に使う。 */
export function dayOfYear(d: Date): number {
  const start = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - start.getTime();
  return Math.floor(diff / 86400000);
}

/** 今日の育児ヒントを1つ返す。 */
export function getTodayTip(d: Date): string {
  return PARENTING_TIPS[dayOfYear(d) % PARENTING_TIPS.length];
}
