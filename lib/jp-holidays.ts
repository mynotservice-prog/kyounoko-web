/**
 * 国民の祝日・振替休日（内閣府「国民の祝日について」の公表分）。
 * 出典: https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv（2026-10-08 に全件を突き合わせ）
 *
 * スポットの定休日（lib/spot-hours.ts）で「月曜休館・祝日は開館して翌平日に休み」を判定するために使う。
 * 載せているのは 2026年10月〜2027年12月。**毎年2月に翌年分が官報で確定したら足す**
 * （範囲の外の日は祝日でない扱いになり、祝日の月曜を「休館」と誤判定する）。
 */
export const JP_HOLIDAYS: ReadonlySet<string> = new Set([
  // 2026
  '2026-10-12', // スポーツの日
  '2026-11-03', // 文化の日
  '2026-11-23', // 勤労感謝の日
  // 2027
  '2027-01-01', // 元日
  '2027-01-11', // 成人の日
  '2027-02-11', // 建国記念の日
  '2027-02-23', // 天皇誕生日
  '2027-03-21', // 春分の日
  '2027-03-22', // 振替休日
  '2027-04-29', // 昭和の日
  '2027-05-03', // 憲法記念日
  '2027-05-04', // みどりの日
  '2027-05-05', // こどもの日
  '2027-07-19', // 海の日
  '2027-08-11', // 山の日
  '2027-09-20', // 敬老の日
  '2027-09-23', // 秋分の日
  '2027-10-11', // スポーツの日
  '2027-11-03', // 文化の日
  '2027-11-23', // 勤労感謝の日
]);

/** この表が持っている最後の日。これより先は祝日を判定できない。 */
export const JP_HOLIDAYS_UNTIL = '2027-12-31';

/** YYYY-MM-DD が祝日・振替休日か。 */
export function isJpHoliday(ymd: string): boolean {
  return JP_HOLIDAYS.has(ymd);
}
