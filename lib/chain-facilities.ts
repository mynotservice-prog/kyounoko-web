export type FacilityValue = {
  /**
   * true=あり(✓) / 'partial'=条件付き・店舗差(△) / false=公式になしと明記(—) /
   * 'unknown'=公式に記載なし（店舗へ確認）。2026-10-24 追加: 公式で裏付けのない ✓/— を出さないため、
   * 行は残したまま「公式に記載なし」と表示する（行を消すと記事の設備語が消え、検索意図に答えられなくなる）
   */
  ok: boolean | 'partial' | 'unknown';
  /** 補足(例: モール内店舗は施設の授乳室を利用) */
  note?: string;
  /**
   * この値の根拠になった公式ページ。セル単位で出典を持てるようにするための任意項目
   * (2026-09-11 追加)。調査ページ(docs/strategy-2026-09.md §5-1)で
   * 「表のどのセルが、どの公式ページの、いつ時点の記述か」を出せることが、
   * 横断比較を出す競合に対する差になる。未設定なら従来どおりチェーン単位の
   * verifiedAt / verifiedMethod が根拠。
   */
  sourceUrl?: string;
  /** セル単位の確認日(YYYY-MM-DD)。項目ごとに改定時期が違うチェーン向け。未設定ならチェーン単位の verifiedAt */
  verifiedAt?: string;
  /** 公式店舗検索の全店集計で、その設備の表示がある店舗数と数えた店舗数（2026-10-24 追加・表示は「n／total店」） */
  stores?: number;
  storesTotal?: number;
  /**
   * 確認方法（2026-10-24 追加）: 'official-site'=公式サイトのページ（FAQ・キッズ/メニュー/アレルギー等）／
   * 'official-store-search'=公式店舗検索の全店集計／'store-contact'=店舗への直接確認。未設定は旧データ（チェーン単位の verifiedMethod を見る）
   */
  method?: 'official-site' | 'official-store-search' | 'store-contact';
  /**
   * 確認範囲（2026-10-24 追加）: 'brand'=ブランド公式ページの全体向けの記載／'some-stores'=公式が一部店舗のみと明記／
   * 'store-count'=店舗検索の全店集計（stores/storesTotal）
   */
  scope?: 'brand' | 'some-stores' | 'store-count';
};

export type ChainFacilities = {
  /** チェーン識別子(slug接頭辞のマッチにも使う) */
  key: string;
  /** 表示名 */
  name: string;
  /** 公式サイト(一次情報への発リンク)。確証がないチェーンは未設定=リンク非表示 */
  officialUrl?: string;
  /** 攻略記事slug(このページで判定ボックスをDB駆動に差し替える) */
  koryakuSlug: string;
  /** データの最終確認日(YYYY-MM-DD)。値を変えたら必ず更新 */
  verifiedAt: string;
  /** 確認手段の明示(E-E-A-T) */
  verifiedMethod: string;
  /**
   * 照合で開いた公式ページ（2026-10-24 追加）。ok:'unknown' のセルは「ここを見て記載がなかった」の意味。
   * items に無い項目は未調査で、'unknown'（調査済み・記載なし）とは区別する
   */
  checkedSources?: string[];
  /** 標準12項目。調査未了の項目は省略可(表示されない) */
  items: Partial<Record<FacilityKey, FacilityValue>>;
  /** チェーン固有の追加行(例: ビッくらポン、低アレルゲンメニュー)。md表からの移行時に情報を落とさないため */
  extras?: Array<{ label: string; value: string }>;
  /**
   * true = 調査・集計用にデータだけ持ち、記事には出さない(2026-09-11 追加)。
   * 攻略記事の判定ボックス置き換え(getChainFacilitiesForArticle)と比較表
   * (getAllChainFacilities)から外れる。公式照合で埋まるセルが少ないチェーンを
   * そのまま登録すると、記事の「子連れチェックリスト」節が数項目に縮むため。
   * 調査ページは getChainFacilitiesForSurvey で全件を読む。
   */
  surveyOnly?: boolean;
};

const V = (
  ok: boolean | 'partial' | 'unknown',
  note?: string,
  meta?: {
    sourceUrl?: string;
    verifiedAt?: string;
    stores?: number;
    storesTotal?: number;
    method?: FacilityValue['method'];
    scope?: FacilityValue['scope'];
  },
): FacilityValue => ({
  ok,
  ...(note ? { note } : {}),
  ...(meta?.sourceUrl ? { sourceUrl: meta.sourceUrl } : {}),
  ...(meta?.verifiedAt ? { verifiedAt: meta.verifiedAt } : {}),
  ...(meta?.stores !== undefined ? { stores: meta.stores, storesTotal: meta.storesTotal } : {}),
  ...(meta?.method ? { method: meta.method } : {}),
  ...(meta?.scope ? { scope: meta.scope } : {}),
});

