/**
 * 駅TOPページ（/station/<駅>）の、駅ごとの例外的な上書き。
 *
 * 【なぜ「テンプレ変更」ではなく「駅ごとの例外」なのか】
 * 駅TOPは563ページが同じテンプレで生成される。テンプレ自体を触ると
 * 2026-09 に判定予定の PR#120（/station/<駅>/<条件> 1,482ページ）の
 * 対照群を全部壊してしまう。駅TOP面はその判定の対照群であるため、
 * 「GSCで個別に問題を立証できた駅だけ」をここに列挙して是正する。
 * 9月の判定では、ここに載っている駅を対照群から除外して集計すること。
 *
 * ここに駅を足すときの条件（2026-08-10 T1分析で定めた運用ルール）:
 *   1. GSCで「検索されている語」と「面名」のズレが実データで示せること
 *   2. 掲載内容そのものが薄い場合は、**内容を直してから**面名を直すこと
 *      （中身が3軒のままタイトルだけ最適化すると、CTRは上がっても
 *        pogo-stick で順位を落とす）
 */

export type StationSeoOverride = {
  title: string;
  description: string;
};

/** 個人店セクションの見出し。モール内テナント中心の駅では既定文言が実態に合わないため差し替える。 */
export type StationIndieLabels = {
  eyebrow: string;
  heading: string;
  lead: string;
  /** TL;DR（30秒でわかる）内の項目名。既定は「個人店・話題店」。 */
  tldrLabel: string;
  /** TL;DR の補足。既定は「雑誌・SNS掲載・人気店」。 */
  tldrNote: string;
};

/**
 * 駅・施設単位で一次情報から確認できた事実のメモ。
 * ここに書けるのは「公式サイトの生HTMLで確認した事実」だけ。
 * 推測・体験・二次情報（まとめサイト等）は書かない。
 */
export type StationFacilityNote = {
  heading: string;
  items: string[];
  /** 確認した一次情報と確認日 */
  source: string;
};

/**
 * 「館（施設）」単位の設備。店の設備とは主体が違うので、絶対に混ぜない。
 *
 * 【なぜ別の型なのか】
 * 2026-08-10 の第1弾で、館の授乳室・おむつ替え台を「店の設備」として書いていた
 * 1軒を削除した。IndieRestaurant の nursingRoom / diaperChangingTable は
 * 「その店が持っている設備」を意味するフィールドで、館の設備を入れてはいけない。
 * 館の設備は館の名前で、館ごとに分けて書く。それがこの型。
 */
export type StationHallFacility = {
  /** 館の名前（公式表記のまま） */
  hall: string;
  /** 館の性格を1行で（屋内/屋外など、貸出ルールの前提になるものだけ） */
  note?: string;
  rows: { label: string; value: string }[];
};

export type StationHallFacilities = {
  heading: string;
  lead: string;
  halls: StationHallFacility[];
  /** 館をまたぐときのルール・館ごとの公式表記が食い違う点 */
  crossHallRules: string[];
  /** 確認した一次情報のURLと確認日 */
  source: string;
};

/**
 * ページ冒頭のH1・リード。SERPのタイトルと着地後の見出しが食い違うと、
 * CTRが上がっても直帰（pogo-stick）で順位を落とすため、seo を上書きした駅は
 * hero も必ずそろえる。
 */
export type StationHeroOverride = {
  h1: string;
  sub: string;
  lead: string;
};

/** TL;DR に足す、この駅だけの追加リンク（他562駅の表示は変えない）。 */
export type StationTldrExtraItem = {
  href: string;
  label: string;
  value: string;
};

export type StationOverride = {
  seo?: StationSeoOverride;
  hero?: StationHeroOverride;
  indieLabels?: StationIndieLabels;
  facilityNote?: StationFacilityNote;
  hallFacilities?: StationHallFacilities;
  tldrExtraItems?: StationTldrExtraItem[];
};

